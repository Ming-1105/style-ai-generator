import unittest

from contracts.models import Brand
from .flagging import flag_candidates, is_user_content
from .test_filtering import candidate


class FlaggingTests(unittest.TestCase):
    def flag(self, image, size=None, text="", website="https://acme.example", domain=None):
        if domain:
            image.source_domain = domain
        return flag_candidates([image], Brand(name="Acme", website=website), {image.url: size} if size else {}, {image.url: text})[0]

    def test_low_resolution_excluded_with_reason(self):
        image = self.flag(candidate("https://cdn.example/car"), (400, 300))
        self.assertTrue(image.flagged)
        self.assertFalse(image.included)
        self.assertIn("400 × 300", image.flag_reason)

    def test_unknown_size_and_ordinary_source_not_flagged(self):
        image = self.flag(candidate("https://cdn.example/car"))
        self.assertFalse(image.flagged)
        self.assertTrue(image.included)
        self.assertIsNone(image.flag_reason)

    def test_retailers_magazines_and_other_brands_sites_are_not_flagged(self):
        for host in ("www.amazon.com", "www.walmart.com", "www.lowes.com", "magazine.example",
                     "press.acme.example", "acme-auto.example", "totally-unrelated.example"):
            for website in ("https://acme.example", ""):
                image = self.flag(candidate("https://cdn.example/car"), domain=host, website=website)
                self.assertFalse(image.flagged, (host, website))
                self.assertTrue(image.included, (host, website))

    def test_ai_generated_clues_are_flagged(self):
        for text in ("AI generated Acme concept", "Midjourney view of the GT", "made with DALL-E", "Stable Diffusion test",
                     "ai-art acme", "Image generated by AI"):
            image = self.flag(candidate("https://cdn.example/car"), text=text)
            self.assertTrue(image.flagged, text)
            self.assertIn("AI-generated", image.flag_reason)
            self.assertFalse(image.included)

    def test_ai_words_inside_other_words_do_not_flag(self):
        for text in ("Airbrush art collection", "Aiden's garage", "Maid art"):
            self.assertFalse(self.flag(candidate("https://cdn.example/car"), text=text).flagged, text)

    def test_fan_made_and_unofficial_clues_are_flagged(self):
        for text in ("Acme fan art", "fanart GT", "fan-made poster", "Unofficial Acme photo", "Acme mock-up", "concept art"):
            image = self.flag(candidate("https://cdn.example/car"), text=text)
            self.assertTrue(image.flagged, text)
            self.assertIn("fan art", image.flag_reason)

    def test_official_renders_are_not_flagged(self):
        for text in ("Official Acme render", "Studio rendering of the GT", "CGI of the new model", "Renderingson collection", "Acme fanatics club"):
            self.assertFalse(self.flag(candidate("https://cdn.example/car"), text=text).flagged, text)

    def test_url_clue(self):
        self.assertTrue(self.flag(candidate("https://cdn.example/fan-art/car.jpg")).flagged)
        self.assertTrue(self.flag(candidate("https://cdn.example/midjourney/car.jpg")).flagged)

    def test_user_generated_and_marketplace_sources_are_flagged(self):
        for host in ("www.reddit.com", "i.imgur.com", "www.ebay.com", "i.ebayimg.com", "www.ebay.nl", "www.marktplaats.nl",
                     "www.instagram.com", "scontent.fbcdn.net", "www.deviantart.com", "www.craigslist.org"):
            image = self.flag(candidate("https://cdn.example/car"), domain=host)
            self.assertTrue(image.flagged, host)
            self.assertIn("user-generated", image.flag_reason)
            self.assertFalse(image.included)

    def test_site_names_inside_other_words_do_not_flag(self):
        self.assertFalse(is_user_content("www.fleabay-shop.example"))
        self.assertFalse(is_user_content("www.redditch-motors.example"))
        self.assertTrue(is_user_content("old.reddit.com"))

    def test_reasons_are_combined_and_the_image_starts_unselected(self):
        image = self.flag(candidate("https://cdn.example/car"), (256, 256), "Acme fan render", domain="www.reddit.com")
        self.assertIn("Small image", image.flag_reason)
        self.assertIn("fan art", image.flag_reason)
        self.assertIn("user-generated", image.flag_reason)
        self.assertFalse(image.included)


if __name__ == "__main__":
    unittest.main()
